import os, time, wave
from contextlib import suppress

import modelscope_patch  # download model weights from ModelScope (CN-friendly, no token)

import simplestart as ss
from pocket_tts import TTSModel
from pocket_tts.data.audio import stream_audio_chunks

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(BASE_DIR, "outputs")
SAMPLES_DIR = os.path.join(BASE_DIR, "assets", "voice_samples")
ACCENT, PANEL_W = "#FF6D00", "760px"
VOICES = ["Alba", "Jean", "Jane", "Anna", "Vera", "George", "Mary", "Azelma", "Paul"]
DEFAULT_TEXT = ("Hello! This voice was generated by SimpleStart, a pure Python web framework. "
                "No JavaScript was written in the making of this app.")
ref_path = ""  # uploaded voice sample; each client runs its own copy of this page, so no cross-user clash

model = TTSModel.load_model(language="english")  # loaded once when a user first opens the page, then reused by every generation
S = ss.session
S.vp_status = S.vp_status or "Ready. First generation loads the model (~10s), then every run is faster than real-time."
S.vp_preview_status = S.vp_preview_status or ""

def voice_code(n): return n.lower().replace(" ", "_")

def on_voice(e):
    preview_player.src = os.path.join(SAMPLES_DIR, f"{voice_code(e.value)}.wav")  # created later, in the UI

def on_upload(e):
    global ref_path
    src = e.value.get("real_path") or ""  # e.value = {"real_path": ..., "name": ...} — info about the uploaded file
    ok = bool(src) and os.path.isfile(src)
    ref_path = src if ok else ""
    S.vp_preview_status = (f"📎 Received {os.path.basename(src)} — 5s of audio, no transcript needed." if ok
                           else "❌ Upload failed, please try again.")
    ss.refresh_page()

@ss.thread  # run in the background, so the page stays responsive while generating
def run_tts(voice, text):
    S.vp_status = "⏳ Generating… page stays responsive meanwhile."
    ss.refresh_page()
    t0 = time.time()
    try:
        os.makedirs(OUT_DIR, exist_ok=True)
        out = os.path.join(OUT_DIR, f"gen_{int(time.time() * 1000)}.wav")
        state = model.get_state_for_audio_prompt(voice)
        stream_audio_chunks(out, model.generate_audio_stream(model_state=state, text_to_generate=text),
                            model.config.mimi.sample_rate)
        elapsed = time.time() - t0
        with wave.open(out) as w: dur = w.getnframes() / w.getframerate()
        S.vp_status = f"⚡ Done in {elapsed:.1f}s — {dur:.1f}s of audio ({dur / elapsed:.1f}x real-time, CPU only)"
        # disk housekeeping: keep only the newest 20 generated files
        gens = sorted((os.path.join(OUT_DIR, f) for f in os.listdir(OUT_DIR) if f.startswith("gen_")),
                      key=os.path.getmtime)  # oldest first
        for f in gens[:-20]:  # everything except the newest 20
            with suppress(OSError): os.remove(f)
        with suppress(Exception):  # if the user refreshed the page meanwhile, `player` is stale — just skip playing
            player.src = out
            player.play()
    except Exception as e:
        S.vp_status = f"❌ {e}"
    finally:
        ss.refresh_page()

def generate():
    text = (ta.value or "").strip()  # component value is kept in sync by the framework — no onchange needed
    if not text:
        S.vp_status = "❌ Please enter some text first."
        ss.refresh_page()
        return
    run_tts(ref_path if ref_path and os.path.isfile(ref_path) else voice_code(sb.value), text)

# ── UI layout ─────────────────────────────────────────────────
with ss.sidebar(position="top", shared=True, style="background-color:#f8fafc; border-bottom:1px solid #e5e7eb; padding:0 16px;"):
    with ss.row(align="center", justify="space-between", no_gutters=True, style="height:56px; flex-wrap:nowrap;"):
        ss.text("🎙️ Voice Playground", tag="b")
with ss.row(justify="center"): ss.text("Text-to-speech & 5-second voice cloning — runs on your CPU, no GPU, no API keys. Powered by Kyutai Pocket TTS.", size="small")
ss.space()
with ss.row(justify="center"):
    with ss.panel(width=PANEL_W, padding=16):
        ta = ss.textarea(label="Text to speak", value=DEFAULT_TEXT, rows=5, maxlength=600, show_word_limit=True)
        sb = ss.selectbox(VOICES, value=VOICES[0], label="Preset Voices", onchange=on_voice)
        with sb.action:
            preview_player = ss.audio(src=os.path.join(SAMPLES_DIR, f"{voice_code(VOICES[0])}.wav"), minimal=True, color="primary", width="fit-content")
        ss.space(16)
        ss.audio(fileType="file", accept="audio/*", dragMode=True, minimal=False, downloadable=False, closable=True, block=True, color=ACCENT, label="Optional: drop a 5s voice sample to clone it (wav / mp3, any language)", onsuccess=on_upload)
        ss.text("@@vp_preview_status", size="small", type="grey-darken-1")
with ss.row(width=PANEL_W, justify="center"): ss.button("🚀 Generate", type="primary", onclick=generate, block=True)
ss.space(16)
with ss.row(justify="center"):
    with ss.panel(width=PANEL_W, padding=16):
        player = ss.audio(downloadable=True, block=True, color=ACCENT)
        ss.space(12)
        ss.text("@@vp_status", size="small", type="grey-darken-1")
with ss.row(justify="center"): ss.text("Built with SimpleStart — this entire app is pure Python, zero JavaScript. TTS engine: Kyutai Pocket TTS (Apache 2.0 / MIT).", size="small")